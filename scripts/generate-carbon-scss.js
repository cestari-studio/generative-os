function writeFileIfChanged(relativePath, content) {
  const fullPath = path.resolve(relativePath);
  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  fs.writeFileSync(fullPath, content, 'utf8');
  console.log(`[scss:generate] Synchronized ${relativePath}`);
}

function main() {
  const args = process.argv.slice(2);
  const scaffoldIdx = args.indexOf('--scaffold');

  const pages = [...PAGE_ARCHETYPES];

  if (scaffoldIdx !== -1 && args[scaffoldIdx + 1]) {
    const rawName = args[scaffoldIdx + 1]
      .toLowerCase()
      .replace(/[^a-z0-9-]/g, '-')
      .replace(/^-+|-+$/g, '');
    const archetypeIdx = args.indexOf('--archetype');
    const archetype = archetypeIdx !== -1 && args[archetypeIdx + 1] ? args[archetypeIdx + 1] : 'dashboard';
    const targetFile = `src/pages/${rawName}/${rawName}.scss`;
    const importPath = `pages/${rawName}/${rawName}`;

    writeFileIfChanged(targetFile, buildScaffoldPageScss(rawName, archetype));

    if (!pages.some((p) => p.importPath === importPath)) {
      pages.push({
        id: rawName,
        block: rawName,
        archetype,
        importPath,
        filePath: targetFile,
      });
    }
  }

  writeFileIfChanged('src/styles/_carbon-foundations.scss', buildFoundationsScss());
  writeFileIfChanged('src/styles/_carbon-generated.scss', buildCarbonGeneratedScss());
  writeFileIfChanged('src/index.scss', buildIndexScss(pages, COMPONENT_STYLESHEETS));
  writeFileIfChanged('src/layouts/page-layout.scss', buildPageLayoutScss());
  writeFileIfChanged('src/pages/dashboard/dashboard.scss', buildDashboardScss());
  writeFileIfChanged('src/pages/welcome/welcome.scss', buildWelcomeScss());
  writeFileIfChanged('src/pages/settings/_tenant-cascade-settings.scss', buildCascadeSettingsScss());
  writeFileIfChanged('src/pages/knowledge/_knowledge-vector-page.scss', buildKnowledgeVectorScss());
  writeFileIfChanged('src/pages/payments/_payment-management-page.scss', buildPaymentManagementScss());
  writeFileIfChanged('src/components/commonHeader/commonHeader.scss', buildCommonHeaderScss());
  writeFileIfChanged('src/components/profilePanel/profile-panel.scss', buildProfilePanelScss());
  writeFileIfChanged('src/components/workspaceSwitcher/workspace-switcher-panel.scss', buildWorkspaceSwitcherScss());
  writeFileIfChanged('src/components/auth/sign-in-modal.scss', buildSignInModalScss());
  writeFileIfChanged('src/components/onboarding/onboarding-full-page.scss', buildOnboardingFullPageScss());
  writeFileIfChanged('src/components/footer/footer.scss', buildFooterScss());
}

main();
