/**
 * Spec Control Plane — deterministic generator (Fase -1 PoC).
 *
 * Emits DECLARATIVE artifacts from validated specs into generated/ — TS types,
 * a declarative form-definition (JSON, NOT React), a traceability row set, a
 * task envelope, and a validation test list. Never emits React components and
 * never changes application behavior. Deterministic: same specs -> same bytes.
 *
 * Usage:
 *   node scripts/spec-generate.mjs            # write generated/
 *   node scripts/spec-generate.mjs --check    # exit 1 if generated/ is stale
 */
import { readFileSync, readdirSync, existsSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SPECS_DIR = process.env.SPEC_DIR_OVERRIDE ? join(process.env.SPEC_DIR_OVERRIDE) : join(ROOT, 'specs');
const GEN_DIR = process.env.SPEC_GEN_OVERRIDE ? join(process.env.SPEC_GEN_OVERRIDE) : join(ROOT, 'generated');
const CHECK = process.argv.includes('--check');
const GENERATOR_VERSION = '1.0.0';

// G1 must pass (or pass-with-review) before generating.
try {
  execFileSync('node', [join(ROOT, 'scripts/spec-validate.mjs')], {
    env: { ...process.env },
    stdio: ['ignore', 'ignore', 'pipe'],
  });
} catch (e) {
  if (e.status === 1) {
    console.error('G1 has BLOCKED findings; refusing to generate. Run spec-validate first.');
    process.exit(1);
  }
  // status 2 = NEEDS_REVIEW -> allowed to generate in plan mode, flagged.
}

function* specFiles(dir) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) yield* specFiles(full);
    else if (/\.(json|ya?ml)$/.test(entry.name)) yield full;
  }
}
const specs = [];
for (const file of specFiles(SPECS_DIR) ?? []) {
  specs.push({ file, spec: JSON.parse(readFileSync(file, 'utf8')) });
}
const byKind = (k) => specs.filter((s) => s.file.includes(`/${k}/`) || s.file.includes(`\\${k}\\`)).map((s) => s.spec);
const journeys = byKind('journeys');
const steps = byKind('steps');
const fields = byKind('fields');
const operations = byKind('operations');
const policies = byKind('policies');

const TYPE_MAP = {
  string: 'string',
  text: 'string',
  boolean: 'boolean',
  integer: 'number',
  date: 'string',
  enum: 'string',
  jsonb: 'Record<string, unknown>',
};

// The repo's copyright hook prepends the IBM header to committed source files.
// Emit the same header here so the generated bytes stay byte-stable across that
// hook (otherwise --check sees the header-injected committed file != fresh output).
const COPYRIGHT_HEADER = [
  '/**',
  ' * Copyright IBM Corp. 2026',
  ' *',
  ' * This source code is licensed under the Apache-2.0 license found in the',
  ' * LICENSE file in the root directory of this source tree.',
  ' */',
  '',
];

// --- Artifact 1: TS types ------------------------------------------------------
// Two field specs may legitimately share a `field_key` (aliases with distinct
// spec_key). Emit each TS identifier ONCE — keyed by the emitted identifier, not
// the spec index. An exact duplicate (same name, same type) is dropped; a
// CONFLICT (same name, different type) is a hard failure — emitting both would
// produce `tsc` TS2300 Duplicate identifier (red-team DEFECT 1).
const emittedTypes = new Map(); // identifier -> tsType
const typeConflicts = [];
for (const f of fields) {
  const name = f.field_key.replace(/[^a-zA-Z0-9]/g, '_');
  const ts = TYPE_MAP[f.data?.type] ?? 'unknown';
  if (emittedTypes.has(name)) {
    if (emittedTypes.get(name) !== ts) {
      typeConflicts.push(`${name}: '${emittedTypes.get(name)}' vs '${ts}' (from ${f.spec_key})`);
    }
    continue; // exact duplicate — already emitted
  }
  emittedTypes.set(name, ts);
}
if (typeConflicts.length > 0) {
  console.error(`SPEC-GENERATE: conflicting TS types for the same identifier: ${typeConflicts.join('; ')}`);
  process.exit(1);
}
const typeLines = [
  ...COPYRIGHT_HEADER,
  '// GENERATED FILE — DO NOT HAND-EDIT. Regenerate: npm run spec:generate',
  `// Generator ${GENERATOR_VERSION}; sources: ${specs.length} specs.`,
  '',
  ...[...emittedTypes.entries()].map(([name, ts]) => `export type ${name} = ${ts};`),
  '',
  ...journeys.map(
    (j) =>
      `export interface ${j.journey_key.replace(/[^a-zA-Z0-9]/g, '_')}JourneySteps {\n${j.steps.map((s) => `  '${s.step_key}': { required_for_dashboard: ${!!s.required_for_dashboard} };`).join('\n')}\n}`,
  ),
  '',
];
const typesTs = typeLines.join('\n');

// --- Artifact 2: declarative form-definition (JSON, NOT React) ----------------
// Steps reference fields by their spec REFERENCE key (spec_key, e.g.
// 'field.person.full-name'), while the field's physical key is `field_key`
// (e.g. 'person.full_name'). Resolve by spec_key — never conflate the two.
// Emit BOTH keys, preserve declared metadata, and FAIL on any unresolvable
// reference (silently dropping metadata is how this defect shipped).
const fieldBySpecKey = new Map(fields.map((f) => [f.spec_key, f]));
const unresolvedRefs = [];
const formDef = {
  generated_by: `spec-generate@${GENERATOR_VERSION}`,
  forms: steps.map((s) => ({
    step_key: s.step_key,
    title: s.title,
    surface_ref: s.surface_ref,
    fields: (s.fields ?? []).map((fk) => {
      const f = fieldBySpecKey.get(fk);
      if (!f) {
        unresolvedRefs.push(`${s.step_key} -> ${fk}`);
        return { ref: fk, unresolved: true };
      }
      return {
        ref: f.spec_key,
        field_key: f.field_key,
        component: f.ui?.component,
        label_key: f.ui?.label_key,
        required: f.rules?.required_when ?? null,
        classification: f.privacy?.classification,
      };
    }),
  })),
};
if (unresolvedRefs.length > 0) {
  console.error(`SPEC-GENERATE: unresolvable field reference(s): ${unresolvedRefs.join(', ')}`);
  process.exit(1);
}
const formDefJson = JSON.stringify(formDef, null, 2) + '\n';

// --- Artifact 3: traceability row set ------------------------------------------
const trace = [];
for (const j of journeys) {
  for (const s of j.steps) {
    const step = steps.find((x) => x.step_key === s.step_key);
    trace.push({
      journey_key: j.journey_key,
      step_key: s.step_key,
      required_for_dashboard: !!s.required_for_dashboard,
      operation_ref: step?.persist?.operation_ref ?? null,
      completion_predicate: step?.completion?.predicate_ref ?? null,
      surface_ref: step?.surface_ref ?? null,
    });
  }
}
const traceJson = JSON.stringify({ generated_by: `spec-generate@${GENERATOR_VERSION}`, rows: trace }, null, 2) + '\n';

// --- Artifact 4: task envelope --------------------------------------------------
const envelope = {
  task_id: 'GENOS-FASE1-POC',
  target: {
    repository: 'cestari-studio/generative-os',
    branch: process.env.GIT_BRANCH ?? 'feat/complete-carbon-page-rebuild',
    baseline_sha: process.env.BASELINE_SHA ?? '0000000000000000000000000000000000000000',
  },
  specs: specs
    .map((s) => s.spec.spec_key)
    .filter(Boolean)
    .sort(),
  mode: 'local_changes_only',
  allowed: ['inspect_source', 'edit_code', 'generate_artifacts', 'run_local_tests', 'propose_migrations'],
  forbidden: [
    'mutate_remote_database',
    'change_remote_auth_or_rls',
    'push_or_merge',
    'deploy_or_promote',
    'modify_protected_identity_record',
  ],
  required_evidence: ['source_references', 'generated_diff', 'test_results', 'unresolved_gaps'],
  acceptance_criteria: ['G1 exit 0/2 with only allowlisted NEEDS_REVIEW', 'generated/ reproducible via --check'],
  stop_conditions: ['any BLOCKED finding', 'unexpected remote mutation requirement'],
};
const envelopeJson = JSON.stringify(envelope, null, 2) + '\n';

// --- Artifact 5: validation test list -------------------------------------------
const testList = [
  '# GENERATED validation test list (declarative; not executed UI)',
  ...operations.flatMap((o) => (o.tests ?? []).map((t) => `- [ ] ${o.operation_key}: ${t}`)),
  ...policies.map((p) => `- [ ] policy ${p.policy_key}: positive + negative authorization`),
  '',
].join('\n');

// --- Write or check --------------------------------------------------------------
const artifacts = {
  'types/spec-types.ts': typesTs,
  'form-definitions/onboarding.person.form.json': formDefJson,
  'traceability/onboarding.person.trace.json': traceJson,
  'envelopes/fase1-poc.envelope.json': envelopeJson,
  'tests/validation-test-list.md': testList,
};

const manifest = { generator_version: GENERATOR_VERSION, files: {} };
for (const [rel, content] of Object.entries(artifacts)) {
  manifest.files[rel] = createHash('sha256').update(content, 'utf8').digest('hex');
}
artifacts['manifest.json'] = JSON.stringify(manifest, null, 2) + '\n';

if (CHECK) {
  let stale = 0;
  for (const [rel, content] of Object.entries(artifacts)) {
    const p = join(GEN_DIR, rel);
    if (!existsSync(p) || readFileSync(p, 'utf8') !== content) {
      console.error(`STALE: ${rel}`);
      stale += 1;
    }
  }
  if (stale > 0) {
    console.error(`${stale} generated file(s) out of date. Run npm run spec:generate.`);
    process.exit(1);
  }
  console.log('generated/ is up to date.');
  process.exit(0);
}

for (const [rel, content] of Object.entries(artifacts)) {
  const p = join(GEN_DIR, rel);
  mkdirSync(join(p, '..'), { recursive: true });
  writeFileSync(p, content, 'utf8');
  console.log(`wrote ${relative(ROOT, p)}`);
}
